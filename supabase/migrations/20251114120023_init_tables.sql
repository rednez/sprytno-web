CREATE OR REPLACE FUNCTION public.create_friend_after_participation()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  task_owner uuid;
begin
  select user_id into task_owner
  from public.tasks
  where id = new.task_id;

  if task_owner is not null and task_owner <> new.user_id then
    insert into public.friends (user_id, friend_id)
    values (new.user_id, task_owner)
    on conflict do nothing;
  end if;

  return new;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.create_participation_message(p_participation_id bigint, p_message text)
 RETURNS bigint
 LANGUAGE plpgsql
 SET search_path TO 'public', 'extensions'
AS $function$
    declare
        v_allowed_sender boolean;
        v_my_uid uuid;
        v_recipient_from_task_owner uuid;
        v_recipient_from_participant uuid;
        v_recipient_id uuid;
        v_new_id bigint;
    begin
        select auth.uid() into v_my_uid;

        -- determine recipient id
        select p.user_id, t.user_id
            from public.participations p
            join public.tasks t on t.id = p.task_id
            where p.id = p_participation_id
            into v_recipient_from_participant, v_recipient_from_task_owner;

        if v_recipient_from_participant <> v_my_uid then
            v_recipient_id := v_recipient_from_participant;
        else
            v_recipient_id := v_recipient_from_task_owner;
        end if;

        insert into public.participations_messages(message, recipient_id, participation_id)
        values (
            public.encrypt_participation_message(p_participation_id, p_message), 
            v_recipient_id, 
            p_participation_id)
        returning id into v_new_id;

        return v_new_id;
    end;
$function$
;

