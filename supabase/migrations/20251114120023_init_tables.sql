CREATE OR REPLACE FUNCTION public.get_nearby_tasks(user_lat double precision, user_lng double precision, distance_meters integer)
 RETURNS TABLE(id bigint, user_id uuid, type public.task_type, title text, description text, repeated_days public.task_day[], is_me boolean, distance_meters integer)
 LANGUAGE sql
 SET search_path TO ''
AS $function$
select
  id,
  user_id,
  type,
  title,
  description,
  repeated_days,
  public.is_me(tasks.user_id) as is_me,
  round(gis.st_distance(public.tasks.location, gis.st_point(user_lng, user_lat)::gis.geography))::int as distance_meters
from
  public.tasks
  where gis.ST_DWithin(
        location,
        gis.ST_SetSRID(gis.ST_MakePoint(user_lng, user_lat), 4326)::gis.geography,
        distance_meters
    ) AND user_id <> (SELECT auth.uid())
  order by location operator(gis.<->) gis.st_point(user_lng, user_lat)::gis.geography;
$function$
;

CREATE OR REPLACE FUNCTION public.get_participation_messages(p_participation_id bigint)
 RETURNS TABLE(id bigint, message text, created_at timestamp with time zone, sender_nickname text, sender_avatar_url text, recipient_nickname text, recipient_avatar_url text, sent_by_me boolean)
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
begin
    return query
        select
            pm.id,
            public.decrypt_participation_message(p_participation_id, pm.message) as message,
            pm.created_at,
            upd_sender.nickname as sender_nickname,
            upd_sender.avatar_url as sender_avatar_url,
            upd_recipient.nickname as recipient_nickname,
            upd_recipient.avatar_url as recipient_avatar_url,
            (pm.sender_id = (select auth.uid())) as sent_by_me
        from participations_messages pm
        join users_public_details upd_sender on upd_sender.user_id = pm.sender_id
        join users_public_details upd_recipient on upd_recipient.user_id = pm.recipient_id
        where pm.participation_id = p_participation_id
        order by created_at asc;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.get_task_details(input_task_id bigint, current_lat double precision DEFAULT NULL::double precision, current_lng double precision DEFAULT NULL::double precision)
 RETURNS TABLE(id bigint, user_id uuid, user_nickname text, user_avatar_url text, type public.task_type, title text, description text, repeated_days public.task_day[], is_me boolean, distance_meters integer, lat double precision, lng double precision, participation_status public.task_participation_status, participation_updated_at timestamp with time zone)
 LANGUAGE sql
 SET search_path TO ''
AS $function$
select
  t.id,
  t.user_id,
  public_details.nickname,
  public_details.avatar_url,
  t.type, 
  t.title, 
  t.description, 
  t.repeated_days, 
  public.is_me(t.user_id) as is_me,
  CASE 
    WHEN current_lat IS NOT NULL AND current_lng IS NOT NULL THEN
      round(gis.st_distance(t.location, gis.st_point(current_lng, current_lat)::gis.geography))::int
    ELSE 
      NULL 
  END AS distance_meters,
  gis.st_y(t.location::gis.geometry) as lat,
  gis.st_x(t.location::gis.geometry) as lng,
  prtcs.status as participation_status,
  prtcs.updated_at as participation_updated_at
FROM public.tasks t
LEFT JOIN public.users_public_details public_details
  ON public_details.user_id = t.user_id
LEFT JOIN public.participations prtcs
  ON prtcs.task_id = t.id
WHERE t.id = input_task_id
$function$
;

